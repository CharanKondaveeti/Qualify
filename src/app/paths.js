/** Canonical URL builders. URLs are context, never authorization. */
export const routes = Object.freeze({
  home: '/', login: '/login', signup: '/signup', forgot: '/forgot-password',
  reset: '/reset-password', callback: '/auth/callback',
  apply: '/institutions/apply', applicationStatus: '/institutions/application-status',
  invitations: '/invitations', platform: '/platform/institutions',
  platformApplications: '/platform/applications', platformSettings: '/platform/settings',
  app: '/app', account: '/app/account',
  institution: id => `/app/i/${encodeURIComponent(id)}`,
  exams: id => `/app/i/${encodeURIComponent(id)}/exams`,
  newExam: id => `/app/i/${encodeURIComponent(id)}/exams/new`,
  exam: (id, examId, tab = 'students') => `/app/i/${encodeURIComponent(id)}/exams/${encodeURIComponent(examId)}/${tab}`,
  banks: id => `/app/i/${encodeURIComponent(id)}/question-banks`,
  calendar: id => `/app/i/${encodeURIComponent(id)}/calendar`,
  reports: id => `/app/i/${encodeURIComponent(id)}/reports`,
  team: id => `/app/i/${encodeURIComponent(id)}/team`,
  invitationsAdmin: id => `/app/i/${encodeURIComponent(id)}/team/invitations`,
  settings: id => `/app/i/${encodeURIComponent(id)}/settings`,
  registerExam: examId => `/join/${encodeURIComponent(examId)}`,
  attempt: (examId, attemptId) => `/candidate/exams/${encodeURIComponent(examId)}/attempts/${encodeURIComponent(attemptId)}`,
  result: attemptId => `/candidate/results/${encodeURIComponent(attemptId)}`,
  demo: '/demo', demoAdmin: '/demo/admin/exams',
  demoStudent: '/demo/student/exam',
});
